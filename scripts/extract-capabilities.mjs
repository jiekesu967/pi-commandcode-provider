/**
 * One-shot generator: pull the Command Code capability snapshot tables out of
 * the installed DSH plugin bundle and emit a dependency-free TypeScript module.
 *
 * The DSH bundle already tracks command-code@1.53.0's model/plan/pricing
 * tables and its authors keep them current; transcribing ~300 entries by hand
 * would only introduce typos. Run once (or again after a Command Code release)
 * and keep the generated capabilities.ts alongside the plugin source.
 *
 *   node _extract-capabilities.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
/** capabilities.ts belongs in the project root, not beside this script. */
const PROJECT_ROOT = dirname(HERE);
const SRC =
	process.env.CC_DSH_BUNDLE ??
	"C:/Users/jieke/.dsh/profiles/web/node_modules/@mars-sea/dsh-commandcode-provider/lib/index.js";

const m = await import(pathToFileURL(SRC).href);

const J = (v) => JSON.stringify(v, null, 2);

const sections = [
	["KNOWN_EFFORTS", J(m.KNOWN_EFFORTS), "Record<string, string[]>"],
	["KNOWN_IMAGE_MODELS", J([...m.KNOWN_IMAGE_MODELS]), "string[]"],
	["KNOWN_THINKING_MODELS", J([...m.KNOWN_THINKING_MODELS]), "string[]"],
	["KNOWN_PLANS", J(m.KNOWN_PLANS), "Record<string, PlanTier>"],
	["PLAN_LABELS", J(m.PLAN_LABELS), "Record<PlanTier, string>"],
	["PLAN_ORDER", J(m.PLAN_ORDER), "Record<PlanTier, number>"],
	["KNOWN_DEALS", J(m.KNOWN_DEALS), "Record<string, { label: string; free?: boolean }>"],
	["KNOWN_PEAK_PRICING", J([...m.KNOWN_PEAK_PRICING]), "string[]"],
	["KNOWN_SUBSCRIPTION_PLANS", J(m.KNOWN_SUBSCRIPTION_PLANS), "Record<string, SubscriptionPlan>"],
];

const header = [
	"/**",
	" * Command Code capability snapshot.",
	" *",
	" * AUTO-GENERATED by _extract-capabilities.mjs from the installed",
	" * @mars-sea/dsh-commandcode-provider bundle (which tracks",
	" * command-code@1.53.0). The Command Code Provider API exposes no plan,",
	" * reasoning-effort, or modality metadata, so these tables are the source",
	" * of truth for the model picker's annotations and for image gating.",
	" *",
	" * Re-run the generator after a Command Code release reshuffles models,",
	" * plans, or prices.",
	" */",
	"",
	"/** Minimum subscription tier a catalog model belongs to. */",
	'export type PlanTier = "go" | "goat" | "pro" | "provider" | "max";',
	"",
	"/** One subscription plan: display name, monthly credit grant, tier rank. */",
	"export interface SubscriptionPlan {",
	"\tname: string;",
	"\tmonthlyCredits: number;",
	"\ttierWeight: number;",
	"}",
	"",
].join("\n");

let out = header;
for (const [name, body, type] of sections) {
	out += `export const ${name}: ${type} = ${body};\n\n`;
}
out += [
	"/** Membership sets for the two modality/effort snapshots above. */",
	"export const KNOWN_IMAGE_MODEL_SET = new Set(KNOWN_IMAGE_MODELS);",
	"export const KNOWN_PEAK_PRICING_SET = new Set(KNOWN_PEAK_PRICING);",
	"",
	"/** Plan-id prefixes, longest first — the CLI's own prefix-match order. */",
	"const SUBSCRIPTION_PLAN_PREFIXES = Object.keys(KNOWN_SUBSCRIPTION_PLANS).sort((a, b) => b.length - a.length);",
	"",
	"/**",
	" * Resolve a subscription `planId` (e.g. `individual-pro-v1`) to its display",
	" * name and monthly credit grant, mirroring the CLI's `getPlanInfo`:",
	" * normalize (lowercase, `_` → `-`), then longest-prefix match so",
	" * `individual-pro-v1` wins over `individual-pro`. Unknown ids return",
	" * `undefined`.",
	" */",
	"export function subscriptionPlanInfo(planId: string): SubscriptionPlan | undefined {",
	"\tconst normalized = planId.toLowerCase().replace(/_/g, \"-\");",
	"\tconst prefix = SUBSCRIPTION_PLAN_PREFIXES.find((candidate) => normalized.startsWith(candidate));",
	"\treturn prefix === undefined ? undefined : KNOWN_SUBSCRIPTION_PLANS[prefix];",
	"}",
	"",
].join("\n");

writeFileSync(join(PROJECT_ROOT, "capabilities.ts"), out, "utf8");
console.log(`wrote capabilities.ts (${out.length} bytes)`);
console.log(
	`efforts=${Object.keys(m.KNOWN_EFFORTS).length} vision=${m.KNOWN_IMAGE_MODELS.size} ` +
		`plans=${Object.keys(m.KNOWN_PLANS).length} catalog-known=${Object.keys(m.KNOWN_PLANS).length}`,
);
